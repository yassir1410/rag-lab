import time
from typing import List, Optional, AsyncIterator
import httpx

from app.core.config import settings
from app.rag.generation.base import (
    BaseLLMProvider,
    GenerationRequest,
    GenerationResponse,
    LLMModelInfo,
    StreamChunk,
)


SUPPORTED_GEMINI_MODELS = [
    LLMModelInfo(
        model_id="gemini-3.8-flash",
        display_name="Gemini 3.8 Flash (Cloud)",
        provider_id="gemini",
        context_window=1048576,
        parameter_count="Proprietary",
        quantization="FP16 / Server",
        supports_streaming=True,
        description="Google state-of-the-art fast multimodal model.",
    ),
    LLMModelInfo(
        model_id="gemini-1.5-flash",
        display_name="Gemini 1.5 Flash (Cloud)",
        provider_id="gemini",
        context_window=1048576,
        parameter_count="Proprietary",
        quantization="FP16 / Server",
        supports_streaming=True,
        description="Google fast, lightweight multimodal model.",
    ),
]


class GeminiProvider(BaseLLMProvider):
    """
    Google Gemini API LLM Provider (Optional cloud provider).
    Requires GEMINI_API_KEY environment variable.
    """

    def __init__(self, api_key: Optional[str] = None):
        self._api_key = api_key or getattr(settings, "GEMINI_API_KEY", None)
        self._base_url = "https://generativelanguage.googleapis.com/v1beta"

    @property
    def provider_id(self) -> str:
        return "gemini"

    @property
    def display_name(self) -> str:
        return "Google Gemini API (Cloud)"

    def is_available(self) -> bool:
        return bool(self._api_key and len(self._api_key.strip()) > 5)

    def list_models(self) -> List[LLMModelInfo]:
        return SUPPORTED_GEMINI_MODELS

    def generate(self, request: GenerationRequest) -> GenerationResponse:
        if not self.is_available():
            raise ValueError("Gemini API key is missing. Set GEMINI_API_KEY in your environment.")

        target_model = request.metadata.get("model") or "gemini-3.8-flash"
        url = f"{self._base_url}/models/{target_model}:generateContent?key={self._api_key}"

        contents = []
        if request.system_prompt:
            contents.append({"role": "user", "parts": [{"text": f"System Instruction: {request.system_prompt}"}]})
            contents.append({"role": "model", "parts": [{"text": "Understood. I will strictly abide by these instructions."}]})
        contents.append({"role": "user", "parts": [{"text": request.prompt}]})

        payload = {
            "contents": contents,
            "generationConfig": {
                "temperature": request.temperature,
                "maxOutputTokens": max(1024, request.max_tokens * 2),
            },
        }

        start_time = time.perf_counter()
        with httpx.Client(timeout=60.0) as client:
            res = client.post(url, json=payload)
            if res.status_code != 200:
                try:
                    err_json = res.json().get("error", {})
                    err_msg = err_json.get("message", res.text)
                    err_status = err_json.get("status") or res.status_code
                    raise ValueError(f"Gemini API Error ({err_status}): {err_msg}")
                except (ValueError, Exception) as parse_err:
                    if isinstance(parse_err, ValueError):
                        raise
                    res.raise_for_status()
            data = res.json()

        latency_ms = (time.perf_counter() - start_time) * 1000.0

        candidates = data.get("candidates", [])
        if not candidates:
            return GenerationResponse(
                content="[No response generated by Gemini]",
                model_id=target_model,
                provider_id="gemini",
                latency_ms=round(latency_ms, 2),
            )

        parts = candidates[0].get("content", {}).get("parts", [])
        text_content = "".join(p.get("text", "") for p in parts)
        usage = data.get("usageMetadata", {})

        return GenerationResponse(
            content=text_content,
            model_id=target_model,
            provider_id="gemini",
            prompt_tokens=usage.get("promptTokenCount"),
            completion_tokens=usage.get("candidatesTokenCount"),
            total_tokens=usage.get("totalTokenCount"),
            latency_ms=round(latency_ms, 2),
            finish_reason=candidates[0].get("finishReason", "stop"),
        )

    async def generate_stream(self, request: GenerationRequest) -> AsyncIterator[StreamChunk]:
        # For simplicity in Phase 06, yield non-streaming result chunk
        resp = self.generate(request)
        yield StreamChunk(content=resp.content, is_final=True, token_count=resp.completion_tokens, finish_reason=resp.finish_reason)
